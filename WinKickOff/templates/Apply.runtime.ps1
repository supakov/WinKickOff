function Mount-DefaultUser {
    # The default user profile, inherited by accounts created from now on.
    $r = & reg.exe load 'HKU\UnattendDefault' 'C:\Users\Default\NTUSER.DAT' 2>&1
    if ($LASTEXITCODE -eq 0) { Write-Log 'default user hive loaded' 'OK'; return $true }
    Write-Log "reg load failed: $r" 'ERROR'
    return $false
}
function Dismount-DefaultUser {
    [gc]::Collect(); [gc]::WaitForPendingFinalizers(); Start-Sleep -Seconds 1
    $r = & reg.exe unload 'HKU\UnattendDefault' 2>&1
    if ($LASTEXITCODE -eq 0) { Write-Log 'default user hive unloaded' 'OK' } else { Write-Log "reg unload: $r" 'WARN' }
}

